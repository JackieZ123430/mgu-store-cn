#!/usr/bin/env python3
"""Bake the Store's Chinese subset. Normal builds use the committed atlas.

python tools/bake_chinese.py /path/to/NotoSansSC.ttf
Requires Pillow; the font is Noto Sans SC (OFL-1.1, src/LICENSE-NotoSansSC.txt).
"""
import base64
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import sys

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / 'src'
FONT_SHA256 = 'a3041811a78c361b1de50f953c805e0244951c21c5bd412f7232ef0d899af0da'

def main():
    font = Path(sys.argv[1])
    if hashlib.sha256(font.read_bytes()).hexdigest() != FONT_SHA256:
        raise SystemExit('Noto Sans SC font SHA-256 mismatch')
    catalog = subprocess.check_output(['node', '-e', 'console.log(JSON.stringify(require(process.argv[1])))', str(SRC/'locale_zh.js')])
    words = json.loads(catalog)
    extra = '汉化：抖音 小白科技杂物社 · BiliBili 小白151 · GitHub JackieZ123430 个应用工具软件包组件网络'
    spec = importlib.util.spec_from_file_location('baker', HERE/'bake_fonts.py')
    baker = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(baker)
    baker.TEXT = ''.join(sorted(set(baker.TEXT + ''.join(words.values()) + extra)))
    atlas = baker.bake(str(font), 36, 500)
    if atlas['atlasW'] > 1024 or atlas['atlasH'] > 2048:
        raise SystemExit('Chinese atlas exceeds reserved 1024 x 2048 budget')
    key = hashlib.sha256(json.dumps(atlas, separators=(',', ':')).encode()).hexdigest()[:16]
    face = {'family': 'Noto Sans SC', 'cacheKey': key, 'sizes': [atlas]}
    (SRC/'font_chinese.js').write_text("'use strict';\n// Noto Sans SC, OFL-1.1; generated by tools/bake_chinese.py.\nmodule.exports = "+json.dumps(face,separators=(',', ':'))+';\n',encoding='utf-8',newline='\n')
    print('Chinese:', len(baker.TEXT), 'glyphs,', atlas['atlasW'], 'x', atlas['atlasH'])

if __name__ == '__main__':
    main()
